def _gh_zip(owner: str, repo: str, ref: str = 'main') -> dict[str, object]:
    return {
        'url': f'https://codeload.github.com/{owner}/{repo}/zip/refs/heads/{ref}',
        'format': 'zip',
        'filename': f'{repo}-{ref}.zip',
        'extract': True,
    }


